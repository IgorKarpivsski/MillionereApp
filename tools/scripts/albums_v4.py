FIRST_SORT = 16


def prompt(subject: str) -> str:
    return f"{subject}, {STYLE}"


def migration() -> str:
    out = [
        "-- Ten more sticker albums (v4), 12 stickers each, next to the 15 v3 albums.",
        "-- Art is bundled in the app as assets/stickers/<slug>_<NN>.webp (tools/scripts/albums_v4.py).",
        "",
        "insert into public.albums (slug, title, blurb, sort, kind) values",
        ",\n".join(f"  ({sql_str(s)}, {sql_str(t)}, {sql_str(b)}, {FIRST_SORT + i}, 'knowledge')"
                   for i, (s, t, b, _) in enumerate(ALBUMS)),
        "on conflict (slug) do nothing;",
        "",
        "insert into public.collectibles (id, album, number, rarity, name_he, position, era, bio_he, art_seed, kind) values",
    ]
    rows = []
    for ai, (slug, _, _, items) in enumerate(ALBUMS):
        assert len(items) == 12, slug
        for n, (name, fact, _subj) in enumerate(items, 1):
            rows.append(f"  ({sql_str(f'{slug}_{n:02d}')}, {sql_str(slug)}, {n}, {sql_str(RARITY[n - 1])}, {sql_str(name)}, "
                        f"'OBJ', 'modern', {sql_str(fact)}, {31500 + ai * 100 + n}, 'object')")
    out.append(",\n".join(rows))
    out.append("on conflict (id) do nothing;")
    return "\n".join(out) + "\n"


if __name__ == '__main__':
    if sys.argv[1] == '--prompts':
        for slug, _, _, items in ALBUMS:
            for n, (_, _, subj) in enumerate(items, 1):
                print(f"{slug}_{n:02d}\t{prompt(subj)}")
    else:
        open(sys.argv[1], 'w').write(migration())
