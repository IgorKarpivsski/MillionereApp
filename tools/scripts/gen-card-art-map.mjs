// Writes apps/mobile/src/features/collection/cardArt.ts — a static require()
// map of every bundled card image (Metro needs literal requires).
// Run after new art lands in apps/mobile/assets/cards: node tools/scripts/gen-card-art-map.mjs
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const dir = join(root, 'apps/mobile/assets/cards');
const ids = readdirSync(dir).filter((f) => f.endsWith('.webp')).map((f) => f.slice(0, -5)).sort();
const lines = ids.map((id) => `  ${id}: require('../../../assets/cards/${id}.webp'),`);
writeFileSync(
  join(root, 'apps/mobile/src/features/collection/cardArt.ts'),
  `// Generated by tools/scripts/gen-card-art-map.mjs — do not edit by hand.\n` +
    `// ${ids.length} illustrated cards; anything missing falls back to the drawn art.\n` +
    `/* eslint-disable @typescript-eslint/no-require-imports */\n` +
    `export const CARD_ART: Record<string, number> = {\n${lines.join('\n')}\n};\n`,
);
console.log(`cardArt.ts: ${ids.length} images`);
