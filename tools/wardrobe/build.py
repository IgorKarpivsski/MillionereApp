"""Builds the app's wardrobe art from raw/ (see download.sh):
apps/mobile/assets/wardrobe/base.webp + items/<id>.webp, and src/features/wardrobe/art.ts with each layer's box."""
import json, pathlib
from PIL import Image
from extract import extract

HERE = pathlib.Path(__file__).parent
ROOT = HERE.parents[1]
OUT = ROOT / 'apps/mobile/assets/wardrobe'
(OUT / 'items').mkdir(parents=True, exist_ok=True)
cat = json.load(open(ROOT / 'content/wardrobe/catalog.json'))
SCALE = 1.0

base = Image.open(HERE / 'raw/base.png').convert('RGB')
cut = Image.open(HERE / 'raw/cut.png').convert('RGBA').resize(base.size)
layers = {}
for i, it in enumerate(cat):
    lay, frac = extract(base, HERE / f'raw/{i}.png')
    if frac > 0.33: print('BAD', it['id'], frac)
    layers[it['id']] = lay

# one frame for everything: the union of the sloth and every item, with a little air
def box(im):
    return im.getchannel('A').point(lambda v: 255 if v > 8 else 0).getbbox()
boxes = [box(cut)] + [box(l) for l in layers.values()]
x0 = max(0, min(b[0] for b in boxes) - 6); y0 = max(0, min(b[1] for b in boxes) - 6)
x1 = min(base.width, max(b[2] for b in boxes) + 6); y1 = min(base.height, max(b[3] for b in boxes) + 6)
W, H = x1 - x0, y1 - y0
cut.crop((x0, y0, x1, y1)).save(OUT / 'base.webp', quality=88, method=6)
meta = {}
for iid, lay in layers.items():
    b = box(lay)
    if not b: print('EMPTY', iid); continue
    b = (max(b[0] - 2, 0), max(b[1] - 2, 0), min(b[2] + 2, base.width), min(b[3] + 2, base.height))
    lay.crop(b).save(OUT / 'items' / f'{iid}.webp', quality=88, method=6)
    meta[iid] = [b[0] - x0, b[1] - y0, b[2] - b[0], b[3] - b[1]]

lines = ['/* eslint-disable @typescript-eslint/no-require-imports */',
         '// Generated by tools/wardrobe/build.py — do not edit by hand.',
         "import type { ImageSourcePropType } from 'react-native';", '',
         f'/** the frame every layer is placed in (px of the source art) */',
         f'export const DOLL_W = {W};', f'export const DOLL_H = {H};',
         "export const DOLL_BASE: ImageSourcePropType = require('../../../assets/wardrobe/base.webp');", '',
         '/** each item: its picture and box [x, y, w, h] inside the frame */',
         'export const LAYERS: Record<string, { src: ImageSourcePropType; box: [number, number, number, number] }> = {']
for iid, b in meta.items():
    lines.append(f"  {iid}: {{ src: require('../../../assets/wardrobe/items/{iid}.webp'), box: [{b[0]}, {b[1]}, {b[2]}, {b[3]}] }},")
lines.append('};')
p = ROOT / 'apps/mobile/src/features/wardrobe/art.ts'; p.parent.mkdir(parents=True, exist_ok=True)
p.write_text('\n'.join(lines) + '\n')
print('frame', W, H, 'items', len(meta))
