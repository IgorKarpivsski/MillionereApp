"""Builds the wardrobe art from the green-keyed edits in rawg/<n>.png (see key.py):
apps/mobile/assets/wardrobe/base.webp, items/<id>.webp (layers), thumbs/<id>.webp (shop pictures)
and src/features/wardrobe/art.ts with each layer's box in one shared frame."""
import json, pathlib
import numpy as np
from PIL import Image
from key import bleed, key

HERE = pathlib.Path(__file__).parent
ROOT = HERE.parents[1]
OUT = ROOT / 'apps/mobile/assets/wardrobe'
for d in ('items', 'thumbs'):
    (OUT / d).mkdir(parents=True, exist_ok=True)
cat = json.load(open(ROOT / 'content/wardrobe/catalog.json'))
SIZE = (860, 1280)
PAD = (86, 256)          # where base.png sits inside base_green.png / base_pad.png
cut = Image.new('RGBA', SIZE, (0, 0, 0, 0))
cut.paste(Image.open(HERE / 'raw/cut.png').convert('RGBA').resize((688, 1024)), PAD)
# no light halo around the fur on dark screens: pull the matte in a little
from PIL import ImageFilter
cut.putalpha(cut.getchannel('A').filter(ImageFilter.MinFilter(5)).filter(ImageFilter.GaussianBlur(0.8)))
cut = bleed(cut)
# where each kind of item may be (y range in the padded frame); anything outside is a stray speck
REGION = {'hat': (0, 520), 'glasses': (380, 640), 'earrings': (380, 760), 'necklace': (560, 1000),
          'bracelet': (700, 1150), 'outfit': (540, 1200), 'shoes': (1000, 1280)}


def box(im):
    return im.getchannel('A').point(lambda v: 255 if v > 10 else 0).getbbox()


layers = {}
for i, it in enumerate(cat):
    p = HERE / f'rawg/{i}.png'
    if not p.exists():
        print('MISSING', i, it['id']); continue
    lay = key(p, SIZE)
    y0, y1 = REGION[it['cat']]
    a = np.asarray(lay.getchannel('A')).copy(); a[:y0] = 0; a[y1:] = 0
    lay.putalpha(Image.fromarray(a))
    frac = (a > 128).mean()
    if frac < 0.002 or frac > 0.35: print('CHECK', it['id'], round(float(frac), 4))
    layers[it['id']] = lay

boxes = [box(cut)] + [box(l) for l in layers.values() if box(l)]
x0 = max(0, min(b[0] for b in boxes) - 6); y0 = max(0, min(b[1] for b in boxes) - 6)
x1 = min(SIZE[0], max(b[2] for b in boxes) + 6); y1 = min(SIZE[1], max(b[3] for b in boxes) + 6)
W, H = x1 - x0, y1 - y0
cut.crop((x0, y0, x1, y1)).save(OUT / 'base.webp', quality=88, method=6)
for f in (OUT / 'items').glob('*.webp'): f.unlink()
meta = {}
T = 192
for iid, lay in layers.items():
    b = box(lay)
    if not b: print('EMPTY', iid); continue
    b = (max(b[0] - 2, 0), max(b[1] - 2, 0), min(b[2] + 2, SIZE[0]), min(b[3] + 2, SIZE[1]))
    piece = lay.crop(b)
    piece.save(OUT / 'items' / f'{iid}.webp', quality=88, method=6)
    meta[iid] = [b[0] - x0, b[1] - y0, b[2] - b[0], b[3] - b[1]]
    # the shop picture: the item alone, centred with a little air, square
    if iid.split('_')[1] in ('earrings', 'bracelet'):
        # a pair far apart: show one of them, big
        from scipy import ndimage as nd
        al = np.asarray(piece.getchannel('A')) > 40
        lab, n = nd.label(nd.binary_dilation(al, iterations=6))
        if n > 1:
            sizes = nd.sum(al, lab, range(1, n + 1))
            sl = nd.find_objects((lab == int(np.argmax(sizes)) + 1).astype(int))[0]
            piece = piece.crop((sl[1].start, sl[0].start, sl[1].stop, sl[0].stop))
    k = (T * 0.86) / max(piece.size)
    sm = piece.resize((max(1, round(piece.width * k)), max(1, round(piece.height * k))), Image.LANCZOS)
    th = Image.new('RGBA', (T, T), (0, 0, 0, 0)); th.alpha_composite(sm, ((T - sm.width) // 2, (T - sm.height) // 2))
    th.save(OUT / 'thumbs' / f'{iid}.webp', quality=90, method=6)

lines = ['/* eslint-disable @typescript-eslint/no-require-imports */',
         '// Generated by tools/wardrobe/build_green.py — do not edit by hand.',
         "import type { ImageSourcePropType } from 'react-native';", '',
         '/** the frame every layer is placed in (px of the source art) */',
         f'export const DOLL_W = {W};', f'export const DOLL_H = {H};',
         "export const DOLL_BASE: ImageSourcePropType = require('../../../assets/wardrobe/base.webp');", '',
         '/** each item: its layer picture, its box [x, y, w, h] inside the frame, and its shop picture */',
         'export const LAYERS: Record<string, { src: ImageSourcePropType; box: [number, number, number, number]; thumb: ImageSourcePropType }> = {']
for iid, b in meta.items():
    lines.append(f"  {iid}: {{ src: require('../../../assets/wardrobe/items/{iid}.webp'), box: [{b[0]}, {b[1]}, {b[2]}, {b[3]}], thumb: require('../../../assets/wardrobe/thumbs/{iid}.webp') }},")
lines.append('};')
(ROOT / 'apps/mobile/src/features/wardrobe/art.ts').write_text('\n'.join(lines) + '\n')
print('frame', W, H, 'items', len(meta))
